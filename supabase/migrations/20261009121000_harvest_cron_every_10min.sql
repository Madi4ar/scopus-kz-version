-- После импорта перечня КОКСНВО в реестре ~200 журналов: один вызов harvest-journals
-- укладывается в лимит времени Edge Function и обрабатывает только часть журналов
-- (недохарвещенные -> никогда не харвещенные -> самые давние), сохраняя
-- resumptionToken. Поэтому запускаем часто: первичный сбор пройдёт за несколько часов,
-- дальше вызовы почти пустые — журнал обновляется не чаще раза в 20 часов.
select cron.alter_job(
  (select jobid from cron.job where jobname = 'harvest-journals-daily'),
  schedule := '*/10 * * * *'
);
